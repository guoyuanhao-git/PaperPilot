RULES = """内置讲解规范：
1. 先形成一句话核心认识，再围绕学生需要理解的问题规划全稿；重新组织论文，不能把报告逐段拆页。研究论文讲清问题、关键机制、证据与边界；综述先建立领域地图，再比较技术分支与未解问题。
2. 一页只讲一个核心观点。除封面保留原题名外，标题尽量写成有依据的结论或机制判断，避免只有“方法”“实验”等栏目名；证据不足时用明确的问题，不编造结论。
3. 关键数字、比较条件和核心结论形成视觉重点，用 emphasis 标出正文中的短语。每页保留必要信息，细节移入 notes，不能用密集小字装下全部论文。
4. 先结合全文材料与全部图表目录选择支撑讲解的关键图表，不按前几张截断，也不强求全放。图文页解释读图顺序、关键结构或趋势及其意义；只有实际提供的图片或原文支持时才描述细节，数字必须带单位和比较条件。
5. 根据内容选择 figure、table、process、equation、columns 或 explain 等版式：方法机制用流程，条件一致的结果用表格，必要公式讲清功能。可编辑文字、表格与流程优先，不把整页报告做成图片，也不为追求变化生造图表或数据。
6. 页面保持清晰层次、适度留白与统一对齐；图表应足够大、保持比例。图文、公式、流程页的文字尤其精简，超出容量就拆页或移入讲稿。默认配色克制，强调色只服务于关键内容。
7. 每页 notes 是老师实际会讲的话：补充概念、解释为什么、给出必要的直观例子并承接下一页，不能照抄页面。自拟例子注明仅帮助理解，区分论文结论与讲解者判断。
8. 收尾提炼贡献、适用边界和一个值得继续思考的问题，不重复摘要和全部实验数字。输出前检查全稿故事连贯、标题与证据相符、页面不重复、信息不过密、图表与说明对应。"""


